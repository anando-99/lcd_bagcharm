# Exports the Ronin look's art (palette, layers, sprites) to roninart.h. Fonts come from questart.h.
import sys, numpy as np
from rpal import P, IDX
import ronin_world as RW, ronin_sprites as RS

out = []
def emit(s): out.append(s)

def rle(a):
    a = list(a.flatten()); res = []; i = 0
    while i < len(a):
        j = i
        while j < len(a) and j - i < 128 and a[j] == a[i]: j += 1
        if j - i >= 3:
            res += [j - i - 1, a[i]]; i = j; continue
        k = i; lit = []
        while k < len(a) and len(lit) < 127:
            j = k
            while j < len(a) and j - k < 3 and a[j] == a[k]: j += 1
            if j - k >= 3: break
            lit.append(a[k]); k += 1
        res += [0x80 + len(lit) - 1] + lit; i = k
    return res

def carr(name, data):
    emit('const uint8_t %s[%d] PROGMEM = {' % (name, len(data)))
    for i in range(0, len(data), 32): emit('  ' + ','.join(str(int(v)) for v in data[i:i + 32]) + ',')
    emit('};')

def grid(rows, cmap, w=None):
    h = len(rows); w = w or max(len(r) for r in rows)
    a = np.zeros((h, w), np.uint8)
    for j, r in enumerate(rows):
        for i, ch in enumerate(r[:w]):
            if ch in cmap and cmap[ch]: a[j, i] = IDX[cmap[ch]]
    return a

def sprite(name, rows, cmap):
    a = grid(rows, cmap)
    emit('#define %s_W %d\n#define %s_H %d' % (name, a.shape[1], name, a.shape[0]))
    carr(name, a.flatten())

emit('// Generated by roninart.py: the Ronin look\'s pixel art (all original). Palette indices, 0 = transparent.')
emit('#pragma once')
emit('#define RPAL_N %d' % len(P))
emit('const uint8_t RPAL[RPAL_N][4] PROGMEM = {')
for n, rgb, k in P: emit('  {%d,%d,%d,%d},  // %s' % (rgb[0], rgb[1], rgb[2], k, n))
emit('};')
for n in ('ink', 'fw', 'R', 'Rd', 'y1', 'y2', 'f0', 'f1', 'f2', 'f3', 'glow', 'crys', 'lp', 'win2', 'mo0', 'mo1', 'mo2', 'W', 'sm0', 'sm1', 's0', 'w1', 'w2', 'tl', 'm2', 'K', 'bronze2'):
    emit('#define RC_%s %d' % (n.upper(), IDX[n]))
W = RW.build_world()
emit('#define RW_W %d\n#define RW_H %d\n#define RW_S %d\n#define RW_N %d\n#define RW_GY0 %d\n#define RW_SX0 %d\n#define RW_SX1 %d'
     % (RW.W, RW.H, RW.S, RW.N, RW.GY(0), RW.SX0, RW.SX1))
carr('RW_RLE', rle(W.a))
far = RW.far_layer(); mid = RW.mid_layer(); fg = RW.fg_layer()
emit('#define RF_H %d' % far.h); carr('RF_RLE', rle(far.a))
emit('#define RM_H %d' % mid.h); carr('RM_RLE', rle(mid.a))
emit('#define RG_H %d' % fg.h); carr('RG_RLE', rle(fg.a))
D = RW.DYN
for k in ('fires', 'lanterns', 'foxeyes', 'banners'):
    emit('#define RD_%s_N %d' % (k.upper(), len(D[k])))
    emit('const int16_t RD_%s[%d][2] = {%s};' % (k.upper(), max(1, len(D[k])), ','.join('{%d,%d}' % p for p in D[k]) or '{0,0}'))
for k in ('bell', 'drum', 'beacon', 'pet', 'castle'):
    emit('const int16_t RD_%s[2] = {%d,%d};' % ((k.upper(),) + tuple(D[k])))
f = np.stack([grid(RS.SAM_FRAMES[n], RS.SAM_MAP, 16) for n in RS.SAM_ORDER])
emit('#define RSAM_W 16\n#define RSAM_H 26\n#define RSAM_N %d' % len(RS.SAM_ORDER))
carr('RSAM', f.flatten())
sprite('RSLASH', RS.SLASH, RS.SAM_MAP)
sprite('RSEATED', RS.SEATED, RS.SAM_MAP)
sprite('RFLAG', RS.FLAG, RS.FLAG_MAP)
emit('const char *const RLOC_NAME[RW_N] = {%s};' % ','.join('"%s"' % n.replace("'", "\\'") for n in RW.LOCS))
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
print('ok', {k: len(v) if isinstance(v, list) else v for k, v in D.items()})
