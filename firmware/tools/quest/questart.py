# Exports the Quest art (palette, layers, sprites, pixel fonts) to questart.h for the firmware.
import sys, numpy as np
from PIL import Image, ImageDraw, ImageFont
from pal import P, IDX
import world, bg, sprites

out = []
def emit(s): out.append(s)

def rle(a):
    a = list(a.flatten()); res = []; i = 0
    while i < len(a):
        j = i
        while j < len(a) and j - i < 128 and a[j] == a[i]: j += 1
        if j - i >= 3:
            res += [j - i - 1, a[i]]; i = j; continue
        k = i; lit = []
        while k < len(a) and len(lit) < 127:
            j = k
            while j < len(a) and j - k < 3 and a[j] == a[k]: j += 1
            if j - k >= 3: break
            lit.append(a[k]); k += 1
        res += [0x80 + len(lit) - 1] + lit; i = k
    return res

def carr(name, data, typ='uint8_t'):
    emit('const %s %s[%d] PROGMEM = {' % (typ, name, len(data)))
    for i in range(0, len(data), 32):
        emit('  ' + ','.join(str(int(v)) for v in data[i:i + 32]) + ',')
    emit('};')

def sprite(name, rows, cmap):
    h = len(rows); w = max(len(r) for r in rows)
    a = np.zeros((h, w), np.uint8)
    for j, r in enumerate(rows):
        for i, ch in enumerate(r):
            if ch in cmap and cmap[ch]: a[j, i] = IDX[cmap[ch]]
    emit('#define %s_W %d\n#define %s_H %d' % (name, w, name, h))
    carr(name, a.flatten())

OVERRIDE = {
  'QF_TITLE': {
    'c': ['.####', '#####', '##...', '##...', '#####', '.####'],
  },
  'QF_BODY': {
    '%': ['XX...X', 'XX..X.', '...X..', '..X...', '.X....', 'X...XX', '....XX'],
    '&': ['.XX..', 'X..X.', 'X.X..', '.X...', 'X.X.X', 'X..X.', '.XX.X'],
  }
}
def font(name, path, size, chars=range(32, 127)):
    F = ImageFont.truetype(path, size)
    glyphs = []; data = []
    asc = F.getmetrics()[0]
    for c in chars:
        ch = chr(c)
        im = Image.new('1', (size * 3, size * 3), 0)
        d = ImageDraw.Draw(im); d.fontmode = '1'
        d.text((size, size), ch, font=F, fill=1)
        a = np.array(im)
        ov = OVERRIDE.get(name, {}).get(ch)
        if ov:
            ref = Image.new('1', (size * 3, size * 3), 0); dr = ImageDraw.Draw(ref); dr.fontmode = '1'; dr.text((size, size), 'H', font=F, fill=1)
            ry = np.nonzero(np.array(ref))[0]; top, bot = ry.min(), ry.max()
            a = np.zeros_like(a)
            for j, row in enumerate(ov):
                for i, px in enumerate(row):
                    if px in 'X#': a[bot - len(ov) + 1 + j, size + i] = 1
        adv = int(round(F.getlength(ch)))
        ys, xs = np.nonzero(a)
        if len(xs) == 0:
            glyphs.append((0, 0, 0, 0, adv, len(data))); continue
        x0, x1, y0, y1 = xs.min(), xs.max(), ys.min(), ys.max()
        g = a[y0:y1 + 1, x0:x1 + 1]
        bpr = (g.shape[1] + 7) // 8
        off = len(data)
        for row in g:
            for b in range(bpr):
                v = 0
                for k in range(8):
                    i = b * 8 + k
                    if i < len(row) and row[i]: v |= 0x80 >> k
                data.append(v)
        glyphs.append((g.shape[1], g.shape[0], x0 - size, y0 - size - asc, adv, off))
    emit('const QGlyph %s_G[%d] PROGMEM = {' % (name, len(glyphs)))
    for g in glyphs: emit('  {%d,%d,%d,%d,%d,%d},' % g)
    emit('};')
    carr(name + '_D', data)
    emit('const QFont %s = {%s_G, %s_D, %d};' % (name, name, name, asc))

emit('// Generated by questart.py: the Quest look\'s pixel art (all original) and two pixel fonts:')
emit('// Jersey 15 and Micro 5 (SIL Open Font Licence 1.1). Palette indices, 0 = transparent.')
emit('#pragma once')
emit('struct QGlyph { uint8_t w, h; int8_t xo, yo; uint8_t adv; uint16_t off; };')
emit('struct QFont { const QGlyph *g; const uint8_t *d; int8_t asc; };')
emit('#define QPAL_N %d' % len(P))
emit('const uint8_t QPAL[QPAL_N][4] PROGMEM = {')
for n, rgb, k in P: emit('  {%d,%d,%d,%d},  // %s' % (rgb[0], rgb[1], rgb[2], k, n))
emit('};')
for n in ('ink', 'ink2', 'fw', 'Wd', 'y0', 'y1', 'y2', 'y3', 'R', 'Rd', 'b0', 'b1', 'b2', 'b3', 'f0', 'f1', 'f2', 'f3', 'glow', 'crys', 'crys2',
          'g0', 'g1', 'g2', 'g3', 'L1', 'L2', 'L3', 'pk', 'pkd', 'q1', 'q2', 'q3', 'v1', 'v2', 'm0', 'm1', 'm2', 't0', 't1', 't2', 't3', 'c2',
          'cl', 'cl2', 'cl3', 'a2', 'a3', 'fy', 'sk', 'sk2', 'tl', 'tl2', 'w1', 'w2', 'p1', 'p2', 'k0', 'k1', 'win', 'win2', 'r1', 'r2', 'hr', 'hr2'):
    emit('#define QC_%s %d' % (n.upper(), IDX[n]))

W, lamps = world.build_world()
emit('#define QW_W %d\n#define QW_Y0 %d\n#define QW_H %d\n#define QW_SPACING %d\n#define QW_NLOC %d\n#define QW_GROUND %d\n#define QW_FEET %d'
     % (world.WW, world.WY0, W.h, world.SPACING, world.NLOC, world.GROUND, world.FEET))
rw = rle(W.a); carr('QW_RLE', rw)
far = bg.far_layer(); hill = bg.hill_layer()
emit('#define QF_W %d\n#define QF_Y0 %d\n#define QF_H %d' % (bg.TW, bg.FAR_Y0, far.h)); carr('QF_RLE', rle(far.a))
emit('#define QH_W %d\n#define QH_Y0 %d\n#define QH_H %d' % (bg.TW, bg.HILL_Y0, hill.h)); carr('QH_RLE', rle(hill.a))
fg = bg.fg_layer()
emit('#define QG_W %d\n#define QG_Y0 %d\n#define QG_H %d' % (bg.FG_W, bg.FG_Y0, fg.h)); carr('QG_RLE', rle(fg.a))
D = world.DYN
emit('// where the animated bits sit, in world coordinates')
for k, v in D.items():
    if k == 'lamps': continue
    emit('const int16_t QD_%s[%d] = {%s};' % (k.upper(), len(v), ','.join(str(int(x)) for x in v)))
emit('#define QLAMP_N %d' % len(lamps))
emit('const int16_t QLAMP[QLAMP_N][2] = {%s};' % ','.join('{%d,%d}' % l for l in lamps))

hf = np.zeros((len(sprites.HERO_ORDER), 26, 16), np.uint8)
for f, nm in enumerate(sprites.HERO_ORDER):
    for j, r in enumerate(sprites.HERO_FRAMES[nm]):
        for i, ch in enumerate(r):
            if ch in sprites.HERO_MAP: hf[f, j, i] = IDX[sprites.HERO_MAP[ch]]
emit('#define QHERO_W 16\n#define QHERO_H 26\n#define QHERO_N %d' % len(sprites.HERO_ORDER))
carr('QHERO', hf.flatten())
sprite('QSLEEP', sprites.SLEEP, sprites.HERO_MAP)
sprite('QBARD', sprites.BARD, sprites.BARD_MAP)
sprite('QNOTE', sprites.NOTE, {'k': 'ink', 'W': 'fw'})
sprite('QCOIN0', sprites.COIN[0], sprites.COIN_MAP)
sprite('QCOIN1', sprites.COIN[1], sprites.COIN_MAP)
sprite('QHEART', sprites.ICON_HEART, sprites.ICON_MAP)
sprite('QSUN', sprites.ICON_SUN, sprites.ICON_MAP)
sprite('QMOON', sprites.ICON_MOON, sprites.ICON_MAP)
sprite('QGEM', sprites.ICON_GEM, sprites.ICON_MAP)
sprite('QHAND', sprites.ICON_HAND, sprites.ICON_MAP)
sprite('QCLOUD0', sprites.CLOUDS[0], sprites.CLOUD_MAP)
sprite('QCLOUD1', sprites.CLOUDS[1], sprites.CLOUD_MAP)
for nm, rows, cm in getattr(sprites, 'EXTRA', []): sprite(nm, rows, cm)

font('QF_TITLE', 'fonts/Jersey15-Regular.ttf', 15)
font('QF_BODY', 'fonts/Micro5-Regular.ttf', 11)
font('QF_BIG', 'fonts/Jersey15-Regular.ttf', 30, chars=range(32, 59))
emit('const char *const QLOC_NAME[QW_NLOC] = {%s};' % ','.join('"%s"' % n.replace("'", "\\'") for n in world.LOCS))

open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
print('rle world', len(rw), 'lamps', len(lamps), 'dyn', {k: v for k, v in D.items() if k != 'lamps'})
