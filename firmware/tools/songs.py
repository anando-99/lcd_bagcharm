def parse(s, tr):
    out=[]
    for t in s.split():
        m=re.fullmatch(r'([A-GR])(#?)(\d?)([sqehw])(\.?)',t)
        if not m: sys.exit('bad token '+t)
        n,sh,o,d,dot=m.groups()
        dur=DUR[d]*(3 if dot else 2)//2
        midi=0 if n=='R' else 12*(int(o)+1)+NOTE[n]+(1 if sh else 0)+tr
        out.append((midi,dur))
    return out
data=[(name,bpm,parse(notes,tr)) for name,bpm,tr,notes in SONGS]
c=['// Generated by songs.py. Public-domain melodies. Each note: MIDI number (0 = rest), length in sixteenths.',
   'struct Song { const char *name; uint8_t bpm; uint16_t n; const uint8_t *notes; };']
for i,(name,bpm,ns) in enumerate(data):
    c.append('const uint8_t SONG%d[] PROGMEM = {%s};'%(i,','.join('%d,%d'%x for x in ns)))
c.append('const Song SONGS[] = {')
for i,(name,bpm,ns) in enumerate(data): c.append('  {"%s", %d, %d, SONG%d},'%(name,bpm,len(ns),i))
c.append('};\n#define SONG_COUNT %d\n'%len(data))
open('songs.h','w').write('\n'.join(c))
js=[{'name':n,'bpm':b,'notes':[x for p in ns for x in p]} for n,b,ns in data]
open('songs.js','w').write('// Generated by songs.py. Same melodies as the charm.\nwindow.SONGS = '+json.dumps(js,separators=(',',':'))+';\n')
for n,b,ns in data: print('%-30s %3d notes %5.1fs'%(n,len(ns),sum(d for _,d in ns)*60/b/4))
