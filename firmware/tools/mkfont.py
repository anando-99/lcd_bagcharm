# Builds 4-bit anti-aliased bitmap fonts (Nunito, SIL Open Font Licence) for the charm.
import sys
from PIL import Image, ImageDraw, ImageFont
D='/tmp/claude-0/-home-claude/1ce155c8-5665-5b42-bccd-aa364e685530/scratchpad/fonts/'
SPEC=[('F_S',D+'fontsource-nunito-5.1.0/package/files/nunito-latin-700-normal.woff',14,' ','~'),
      ('F_M',D+'fontsource-nunito-5.1.0/package/files/nunito-latin-800-normal.woff',19,' ','~'),
      ('F_L',D+'fontsource-nunito-5.1.0/package/files/nunito-latin-800-normal.woff',28,' ','~'),
      ('F_XL',D+'fontsource-nunito-5.1.0/package/files/nunito-latin-900-normal.woff',64,'%',':')]
out=['// Generated by mkfont.py from Nunito (SIL Open Font Licence 1.1). 4 bits per pixel, rows packed.',
     'struct AAGlyph { uint32_t off; uint8_t w, h; int8_t dx, dy; uint8_t adv; };',
     'struct AAFont  { const uint8_t *bmp; const AAGlyph *g; uint8_t first, last, lineH, ascent; };','']
total=0
for name,path,px,first,last in SPEC:
    f=ImageFont.truetype(path,px)
    asc,desc=f.getmetrics()
    bmp=[];glyphs=[]
    for code in range(ord(first),ord(last)+1):
        ch=chr(code)
        adv=round(f.getlength(ch))
        bb=f.getbbox(ch)
        if bb[2]<=bb[0] or bb[3]<=bb[1]:
            glyphs.append((len(bmp),0,0,0,0,adv));continue
        w,h=bb[2]-bb[0],bb[3]-bb[1]
        im=Image.new('L',(w,h),0); ImageDraw.Draw(im).text((-bb[0],-bb[1]),ch,font=f,fill=255)
        px_=im.load(); off=len(bmp)
        for y in range(h):
            row=[(px_[x,y]+8)//17 for x in range(w)]
            if len(row)%2: row.append(0)
            for i in range(0,len(row),2): bmp.append((row[i]<<4)|row[i+1])
        glyphs.append((off,w,h,bb[0],bb[1]-asc,adv))
    total+=len(bmp)
    out.append('const uint8_t %s_bmp[] PROGMEM = {'%name)
    for i in range(0,len(bmp),24): out.append('  '+','.join('0x%02X'%b for b in bmp[i:i+24])+',')
    out.append('};')
    out.append('const AAGlyph %s_g[] PROGMEM = {'%name)
    for g in glyphs: out.append('  {%d,%d,%d,%d,%d,%d},'%g)
    out.append('};')
    out.append('const AAFont %s = { %s_bmp, %s_g, %d, %d, %d, %d };'%(name,name,name,ord(first),ord(last),asc+desc,asc))
    out.append('')
open(sys.argv[1],'w').write('\n'.join(out))
print('bytes',total)
